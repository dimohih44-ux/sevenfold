def qid(seed):
    """Стабильный 16-символьный hex-ид."""
    h = hashlib.md5(seed.encode("utf-8")).hexdigest()[:15]
    return "1" + h.upper()


def item_task(item, count=1, consume=True, seed=""):
    return ('{ id: "%s" item: { count: %d, id: "%s" } type: "item" consume_items: %s }'
            % (qid("task" + seed + item), count, item, "true" if consume else "false"))


def adv_task(adv, seed=""):
    return '{ id: "%s" advancement: "%s" criterion: "" type: "advancement" }' % (qid("adv" + seed + adv), adv)


def item_reward(item, count=1, seed=""):
    return '{ id: "%s" item: { count: %d, id: "%s" } type: "item" }' % (qid("rw" + seed + item), count, item)


def quest(title, desc, task, x, y, deps=(), rewards=(), subtitle=""):
    lines = []
    lines.append("\t\t{")
    if deps:
        lines.append("\t\t\tdependencies: [ %s ]" % " ".join('"%s"' % d for d in deps))
    lines.append("\t\t\tdescription: [")
    for d in desc:
        lines.append('\t\t\t\t"%s"' % d.replace('"', '\\"'))
    lines.append("\t\t\t]")
    lines.append('\t\t\tid: "%s"' % qid("q" + title))
    if rewards:
        lines.append("\t\t\trewards: [")
        for r in rewards:
            lines.append("\t\t\t\t" + r)
        lines.append("\t\t\t]")
    if subtitle:
        lines.append('\t\t\tsubtitle: "%s"' % subtitle)
    lines.append("\t\t\ttasks: [ %s ]" % task)
    lines.append('\t\t\ttitle: "%s"' % title)
    lines.append("\t\t\tx: %sd" % x)
    lines.append("\t\t\ty: %sd" % y)
    lines.append("\t\t}")
    return "\n".join(lines)


def img_entry(path, x, y, w, h, alpha=255, rot=0, locked=True, salt=""):
    return ("\t\t{\n\t\t\talpha: %d\n\t\t\tcorner: true\n\t\t\theight: %sd\n\t\t\tid: \"%s\"\n"
            "\t\t\timage: \"%s\"\n\t\t\torder: 1\n\t\t\tposition_locked: %s\n\t\t\trotation: %sd\n"
            "\t\t\twidth: %sd\n\t\t\tx: %sd\n\t\t\ty: %sd\n\t\t}"
            % (alpha, h, qid("imgobj" + salt + path + str(x) + str(y)), path,
               "true" if locked else "false", rot, w, x, y))


