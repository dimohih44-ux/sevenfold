def chapter(fname, title, icon, order, quests, subtitle="", extra=None):
    body = ",\n".join(quests)
    sub = ""  # подписи глав на холсте не нужны

    # декор на холсте отключён: фон задаёт тема, лишние PNG в редакторе мешают
    entries = []
    img = "\n\timages: [\n%s\n\t]" % ",\n".join(entries)
    text = """{
\talways_invisible: false
\tdefault_hide_dependency_lines: false
\tdefault_quest_shape: ""
\tfilename: "%s"
\tgroup: ""
\ticon: "%s"
\tid: "%s"
\torder_index: %d
\tquest_links: [ ]
\tquests: [
%s
\t]%s%s
\ttitle: "%s"
}
""" % (fname, icon, qid("chapter" + fname), order, body, img, sub, title)
    (QROOT / "chapters" / (fname + ".snbt")).parent.mkdir(parents=True, exist_ok=True)
    (QROOT / "chapters" / (fname + ".snbt")).write_text(text, encoding="utf-8")
    return text


